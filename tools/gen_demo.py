"""Usage: HEADLESS=./headless BIOS=StandardBios.v32 ROM=Rockfield.v32 python3 gen_demo.py [games]

Plays several scripted games in the headless emulator and turns the
best recording (as saved on the memory card) into demo_builtin.h."""
import random, struct, subprocess, os, sys
H=os.environ.get('HEADLESS','./headless'); BIOS=os.environ.get('BIOS','StandardBios.v32')
REC_WORDS=720

def script(seed):
    r=random.Random(seed); L=[(460,464,4)]; f=520
    while f<6000:
        L.append((f,f+4,6))                                   # fire taps
        if r.random()<0.6: L.append((f,f+r.randint(5,16),r.choice([0,1])))   # turn
        if r.random()<0.12: L.append((f,f+r.randint(8,20),2))                # thrust
        if r.random()<0.01: L.append((f,f+2,7))                              # hyperspace
        if r.random()<0.04: L.append((f,f+r.randint(30,70),8))               # shield
        f+=r.randint(8,15)
    return '\n'.join('%d %d %d'%x for x in L)

def read_card(path):
    d=open(path,'rb').read()
    w=lambda i: struct.unpack('<i',d[8+4*i:12+4*i])[0]
    return dict(seed=w(31),frames=w(32),score=w(33),data=[w(40+i) for i in range(REC_WORDS)])

best=None
for k in range(int(sys.argv[1]) if len(sys.argv)>1 else 6):
    open('gen.txt','w').write(script(k))
    if os.path.exists('gen.card'): os.remove('gen.card')
    os.makedirs('genf',exist_ok=True)
    env=dict(os.environ,MEMCARD='gen.card',INPUT_SCRIPT='gen.txt',FRAME_FROM='999999')
    subprocess.run([H,BIOS,os.environ.get('ROM','Rockfield.v32'),'genf','6200','1000'],env=env,capture_output=True)
    c=read_card('gen.card')
    print('script',k,'score',c['score'],'frames',c['frames'])
    if c['frames']>0 and (best is None or c['score']>best['score']): best=c

rows=',\n    '.join(', '.join('0x%08X'%(v&0xFFFFFFFF) for v in best['data'][i:i+8]) for i in range(0,REC_WORDS,8))
open(os.environ.get('OUT','demo_builtin.h'),'w').write(f'''// generated by gen_demo.py: the recording shown in attract mode
// until a player sets a better game (score {best['score']}, {best['frames']} frames)
int builtin_demo_seed = {best['seed']};
int builtin_demo_frames = {best['frames']};
int builtin_demo_score = {best['score']};
int[ REC_WORDS ] builtin_demo_data =
{{
    {rows}
}};
''')
print('chosen: score',best['score'],'frames',best['frames'],'seed',best['seed'])
